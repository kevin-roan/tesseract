const NOW = Date.parse("2026-09-23T12:00:00.000Z");
const USAGE = { input_tokens: 10, output_tokens: 20, cache_creation_input_tokens: 30, cache_read_input_tokens: 40 };

type Line = Record<string, unknown>;

const user = (content: unknown, extra: Line = {}): Line => ({
  type: "user",
  timestamp: "2026-09-23T10:00:00.000Z",
  message: { role: "user", content },
  ...extra,
});

const assistant = (id: string, text: string, extra: { model?: string; timestamp?: string; requestId?: string; usage?: Line } = {}): Line => ({
  type: "assistant",
  timestamp: extra.timestamp ?? "2026-09-23T10:01:00.000Z",
  ...(extra.requestId ? { requestId: extra.requestId } : {}),
  message: {
    id,
    role: "assistant",
    model: extra.model ?? "claude-opus-4-5",
    usage: extra.usage ?? USAGE,
    content: [{ type: "text", text }],
  },
});

const jsonl = (lines: Line[], cwd: string, sessionId: string) =>
  lines.map((line) => JSON.stringify({ sessionId, cwd, ...line })).join("\n") + "\n";

function writeTranscript(root: string, cwd: string, sessionId: string, lines: Line[], mtimeMs = NOW): string {
  const dir = join(root, "projects", cwd.replace(/[^A-Za-z0-9]/g, "-"));
  mkdirSync(dir, { recursive: true });
  const path = join(dir, `${sessionId}.jsonl`);
  writeFileSync(path, jsonl(lines, cwd, sessionId));
  utimesSync(path, mtimeMs / 1000, mtimeMs / 1000);
  return path;
}

async function fileAt(path: string, sessionId: string): Promise<TranscriptFile> {
  const stats = await Bun.file(path).stat();
  return { path, sessionId, subagent: false, size: stats.size, mtimeMs: stats.mtimeMs };
}

